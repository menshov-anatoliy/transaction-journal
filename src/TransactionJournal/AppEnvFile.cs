using DotNetEnv;

namespace TransactionJournal;

/// <summary>
/// Загрузчик локального файла .env: переносит значения из файла в переменные
/// окружения процесса до первого обращения к ним потребителей конфигурации
/// (прежде всего — поставщика учётных данных Bybit).
/// </summary>
public static class AppEnvFile
{
	/// <summary>
	/// Ищет файл .env от текущего каталога вверх по дереву каталогов и загружает
	/// найденные значения в переменные окружения процесса до первого обращения к ним.
	/// </summary>
	// Файл ищется от текущего каталога вверх, поэтому .env находится и при запуске
	// из каталога проекта, и из корня репозитория; отсутствие файла — штатный путь:
	// метод завершается без исключений, переменные остаются такими, какими их
	// задало системное окружение.
	// Traceability: openspec:config/env-file#requirement-env-file-loaded-on-startup
	// Уже заданные в окружении переменные сохраняют системное значение: значение из
	// .env применяется только к переменным, которые ещё не определены в процессе.
	// Traceability: openspec:config/env-file#requirement-system-vars-take-precedence
	public static void Load()
	{
		Env.TraversePath().NoClobber().Load();
	}
}
