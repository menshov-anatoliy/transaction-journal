namespace TransactionJournal.Analytics;

/// <summary>
/// Вид записи единого потока позиции для движка FIFO: сделка исполнения либо
/// закрывающая запись — биржевая запись экспирации или ручная пометка пользователя.
/// Вид задаёт ранг устойчивости хронологии: при равном моменте сделка применяется
/// раньше биржевой закрывающей записи, биржевая — раньше ручной пометки.
// Traceability: openspec:analytics/performance#requirement-realized-pnl-own-fifo
/// </summary>
public enum PositionFifoEntryKind
{
	/// <summary>Сделка исполнения: знаковое количество по цене исполнения с комиссией записи исполнения.</summary>
	Trade,

	/// <summary>Биржевая закрывающая запись экспирации: delivery по внутренней стоимости либо OTM-экспирация по нулю.</summary>
	ExpiryClosing,

	/// <summary>Ручная пометка закрытия пользователя: цена пользователя либо последняя известная марка инструмента.</summary>
	ManualMark,
}
