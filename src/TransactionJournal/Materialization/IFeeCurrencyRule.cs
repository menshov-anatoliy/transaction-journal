namespace TransactionJournal.Materialization;

/// <summary>
/// Правило разбора валюты комиссии: приводит валюту биржевой записи исполнения
/// к валюте журнала. Правило выделено в самостоятельную зависимость материализатора,
/// чтобы уточнение разбора (например, знак rebate или новые паритеты валют) применялось
/// повторной сборкой доменных представлений из сырых записей — без правок остального
/// конвейера и без повторного обращения к бирже.
/// Traceability: change:add-bybit-sync/design#d7
/// </summary>
public interface IFeeCurrencyRule
{
	/// <summary>Приводит валюту комиссии биржевой записи к валюте журнала; null — биржа валюту не указала.</summary>
	/// <param name="feeCurrency">Валюта комиссии из сырой записи (например, USDC, USDT, BTC).</param>
	/// <returns>Каноническая валюта журнала либо null, если биржа валюту не указала.</returns>
	string? Canonicalize(string? feeCurrency);
}
