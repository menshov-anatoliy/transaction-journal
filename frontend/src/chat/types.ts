/**
 * Доменные типы чата агента на стороне SPA. Контракт зеркалит решения
 * change add-agent-chat (домен и хранение — его задачи), пока эндпоинты
 * не реализованы бэкендом: API-клиент и runtime строятся на этих типах,
 * а задача 5.3 подключит их к реальным ответам /api/v1.
 */

/** Категория источника данных — закрытый справочник из трёх значений. */
export type ChatDataSource = "journal" | "rules-corpus" | "market";

/**
 * Параметры чата — фиксируются при создании первым сообщением: ИИ-модель,
 * опциональная привязка к конструкции и набор источников данных. Привязка
 * неизменяема — сменить контекст значит начать новый чат.
 */
export interface ChatParams {
	/** ИИ-модель чата; дефолт и возможные значения задаёт бэкенд (GLM-5.3). */
	model: string;
	/** Необязательная привязка к конструкции; отсутствует у портфельных чатов. */
	constructionId?: string | null;
	/** Подмножество справочника источников; по умолчанию все три категории. */
	sources: readonly ChatDataSource[];
}

/** Жизненный цикл чата: активен до ручного завершения владельцем. */
export type ChatStatus = "active" | "completed";

/**
 * Чат агента как запись окружения: плоская полная история обмена
 * с параметрами и статусом; создаётся первым сообщением владельца.
 */
export interface ChatDto {
	id: string;
	status: ChatStatus;
	params: ChatParams;
	/** Момент создания чата первым сообщением, ISO 8601. */
	createdAt: string;
	/** Момент последнего сообщения чата, ISO 8601. */
	lastMessageAt: string;
}

/** Роль автора сообщения чата. */
export type ChatMessageRole = "user" | "assistant";

/**
 * Вызов инструмента источника, зафиксированный в следе источников:
 * какой инструмент, с каким аргументом и на каких данных (as-of).
 * Рыночный след — частный случай: недоступность биржи даёт кэш с as-of.
 */
export interface ToolCallTrace {
	/** Имя инструмента реестра: read_rule_card, get_market_snapshot, get_option_board. */
	tool: string;
	/** Аргумент вызова: id карточки правила или baseCoin. */
	argument: string;
	/** Отметка as-of использованных данных, ISO 8601. */
	asOf?: string;
	/** Инструмент ответил кэшем из-за недоступности рынка. */
	degraded?: boolean;
}

/** Ссылка следа источников на карточку правила или данные журнала. */
export interface SourceReference {
	kind: "rule-card" | "journal";
	/** Идентификатор карточки правила или записи журнала. */
	id: string;
	/** Краткое название для отображения ссылки. */
	title: string;
	/** Отметка as-of данных по ссылке, ISO 8601. */
	asOf: string;
}

/**
 * След источников в ответе ИИ-помощника: использованные инструменты
 * и ссылки на карточки правил и данные журнала с их отметками as-of.
 */
export interface SourceTrace {
	toolCalls: readonly ToolCallTrace[];
	references: readonly SourceReference[];
}

/**
 * Сообщение чата: роль, текст и отметка as-of; ответ ИИ-помощника
 * дополнительно несёт след источников.
 */
export interface ChatMessageDto {
	id: string;
	role: ChatMessageRole;
	text: string;
	/** Момент сообщения, ISO 8601. */
	asOf: string;
	/** След источников — только у ответов ИИ-помощника. */
	sourceTrace?: SourceTrace;
}
