import { describe, expect, it } from "vitest";
import { formatAmount, formatSignedAmount, formatSignedPercent } from "./quantity";

// Форматы величин журнала — единый слой без дублирования форматтеров по
// экранам (перенос №25). Эталоны знаковых величин унаследованы от сводки
// списка конструкций: «+214.32» / «-58.2» / «0», проценты — «+8.6%» / «-3.1%»
// / «0%», абсолютные суммы — «3000». Разделитель — точка, дробные нули
// без хвоста.
// Traceability: doc:.wf-research/ui-concept/concept.md#12-карта-переноса-по-инвентаризации-129

describe("формат суммы без знака", () => {
	it.each([
		[3000, "3000"],
		[214.32, "214.32"],
		[0.5, "0.5"],
		[0, "0"],
		[-58.2, "-58.2"],
		[123.456, "123.46"],
	])("%p → «%s»", (value, expected) => {
		// Act: абсолютная величина форматируется без знака «плюс».
		const text = formatAmount(value);

		// Assert: до двух дробных знаков, без хвостовых нулей.
		expect(text).toBe(expected);
	});
});

describe("формат знаковой суммы USDT", () => {
	it.each([
		[214.32, "+214.32"],
		[-58.2, "-58.2"],
		[3, "+3"],
		[0, "0"],
		[-0.05, "-0.05"],
		[0.1, "+0.1"],
	])("%p → «%s»", (value, expected) => {
		// Act: величина PnL форматируется со знаком при числе.
		const text = formatSignedAmount(value);

		// Assert: рост — с «плюсом», падение — с «минусом», ноль — без знака.
		expect(text).toBe(expected);
	});
});

describe("формат знакового процента", () => {
	it.each([
		[8.6, "+8.6%"],
		[-3.1, "-3.1%"],
		[0.5, "+0.5%"],
		[0, "0%"],
		[12.34, "+12.3%"],
	])("%p → «%s»", (value, expected) => {
		// Act: процент от капитала форматируется со знаком и суффиксом.
		const text = formatSignedPercent(value);

		// Assert: один дробный знак, без хвостовых нулей, ноль без знака.
		expect(text).toBe(expected);
	});
});
