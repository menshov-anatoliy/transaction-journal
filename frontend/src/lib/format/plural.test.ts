import { describe, expect, it } from "vitest";
import { formatCount, pluralForm } from "./plural";

// Русские формы числительных — общий слой форматирования без дублирования
// по экранам (перенос №25: «1 конструкция / 2 конструкции / 5 конструкций»,
// «открыта / открыты / открыто»).
// Traceability: doc:.wf-research/ui-concept/concept.md#12-карта-переноса-по-инвентаризации-129

const constructionForms = { one: "конструкция", few: "конструкции", many: "конструкций" } as const;
const openForms = { one: "открыта", few: "открыты", many: "открыто" } as const;

describe("форма русского числительного по количеству", () => {
	it.each([
		[1, "конструкция"],
		[2, "конструкции"],
		[4, "конструкции"],
		[5, "конструкций"],
		[0, "конструкций"],
		[11, "конструкций"],
		[12, "конструкций"],
		[14, "конструкций"],
		[21, "конструкция"],
		[22, "конструкции"],
		[101, "конструкция"],
		[111, "конструкций"],
	])("количество %i даёт форму «%s»", (count, expected) => {
		// Act: выбирается форма слова «конструкция» по числу.
		const form = pluralForm(count, constructionForms);

		// Assert: форма следует правилам русской грамматики.
		expect(form).toBe(expected);
	});

	it.each([
		[1, "открыта"],
		[3, "открыты"],
		[6, "открыто"],
		[11, "открыто"],
		[24, "открыты"],
	])("количество %i даёт форму «%s»", (count, expected) => {
		// Act: выбирается форма причастия «открыта» по числу.
		const form = pluralForm(count, openForms);

		// Assert: тот же закон склонения, что и для существительных.
		expect(form).toBe(expected);
	});
});

describe("подпись количества со словом в верной форме", () => {
	it.each([
		[5, "5 конструкций"],
		[21, "21 конструкция"],
		[2, "2 конструкции"],
		[0, "0 конструкций"],
	])("%i → «%s»", (count, expected) => {
		// Act: счётчик превращается в готовую подпись.
		const label = formatCount(count, constructionForms);

		// Assert: число и слово согласованы одной строкой.
		expect(label).toBe(expected);
	});
});
